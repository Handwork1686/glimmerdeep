def glyph_canvas(rows: list[str]) -> Canvas:
    w = max((len(r) for r in rows), default=1)
    cv = Canvas(w, CELL_H)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == "#":
                cv.px(x, y, c("light4") if False else (255, 255, 255, 255))
    return cv


def build(outlined: bool) -> tuple[Canvas, str]:
    glyphs: dict[str, Canvas] = {}
    for k, v in {**U, **L}.items():
        glyphs[k] = glyph_canvas(v)
    glyphs[" "] = Canvas(3, CELL_H)
    pad = 1 if outlined else 0
    gw = 7 + pad * 2
    gh = CELL_H + pad * 2
    cols = 16
    keys = sorted(glyphs.keys(), key=ord)
    rows = (len(keys) + cols - 1) // cols
    sheet = Canvas(cols * gw, rows * gh)
    chars = []
    for i, k in enumerate(keys):
        g = glyphs[k]
        if outlined:
            g = g.padded(1).outline(c("void0"), diagonal=True)
        gx, gy = (i % cols) * gw, (i // cols) * gh
        sheet.blit(g, gx, gy)
        adv = glyphs[k].w + 1
        chars.append(
            f'<char id="{ord(k)}" x="{gx}" y="{gy}" width="{g.w}" height="{g.h}" '
            f'xoffset="{-pad}" yoffset="{-pad}" xadvance="{adv}" page="0" chnl="15"/>'
        )
    name = "pixel_o" if outlined else "pixel"
    xml = (
        f'<?xml version="1.0"?>\n<font>\n<info face="{name}" size="9" bold="0" italic="0" charset="" unicode="1" '
        f'stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="0,0" outline="{pad}"/>\n'
        f'<common lineHeight="11" base="7" scaleW="{sheet.w}" scaleH="{sheet.h}" pages="1" packed="0"/>\n'
        f'<pages><page id="0" file="{name}.png"/></pages>\n<chars count="{len(chars)}">\n'
        + "\n".join(chars) + "\n</chars>\n</font>\n"
    )
    return sheet, xml
